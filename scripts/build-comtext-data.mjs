import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const COMMIT = "ee8c2432fb4229012a3cb396b7823639216fc3da";
const BASE_URL = `https://raw.githubusercontent.com/ICEF-NLP/COMtext.SR/${COMMIT}/data`;
const SOURCES = Object.freeze({
  ekavian: `${BASE_URL}/comtext.sr.legal.ekavica.conllu`,
  ijekavian: `${BASE_URL}/comtext.sr.legal.ijekavica.conllu`
});

async function download(url) {
  const response = await fetch(url, { headers: { "User-Agent": "Prepisi-data-builder" } });
  if (!response.ok) throw new Error(`Download failed (${response.status}): ${url}`);
  return response.text();
}

function tokens(conllu) {
  return conllu.split(/\r?\n/u)
    .filter((line) => /^\d+\t/u.test(line) && !/^\d+[-.]\d*\t/u.test(line))
    .map((line) => {
      const fields = line.split("\t");
      return Object.freeze({
        id: fields[0], form: fields[1], lemma: fields[2], upos: fields[3], msd: fields[4]
      });
    });
}

function compile(ekavianText, ijekavianText) {
  const ekavian = tokens(ekavianText);
  const ijekavian = tokens(ijekavianText);
  if (ekavian.length !== ijekavian.length) {
    throw new Error(`Token count mismatch: ${ekavian.length} / ${ijekavian.length}`);
  }

  const pairOccurrences = new Map();
  const lemmaPairOccurrences = new Map();
  for (let index = 0; index < ekavian.length; index += 1) {
    const ek = ekavian[index];
    const ij = ijekavian[index];
    if (ek.id !== ij.id || ek.upos !== ij.upos || ek.msd !== ij.msd) {
      throw new Error(`Morphological alignment mismatch at token ${index + 1}`);
    }

    const ekForm = ek.form.toLocaleLowerCase("sr");
    const ijForm = ij.form.toLocaleLowerCase("sr");
    if (ekForm === ijForm || !/^\p{L}+$/u.test(ekForm) || !/^\p{L}+$/u.test(ijForm)) continue;
    const key = `${ekForm}\u0000${ijForm}`;
    pairOccurrences.set(key, (pairOccurrences.get(key) || 0) + 1);

    const ekLemma = ek.lemma.toLocaleLowerCase("sr");
    const ijLemma = ij.lemma.toLocaleLowerCase("sr");
    if (ekLemma !== ijLemma && /^\p{L}+$/u.test(ekLemma) && /^\p{L}+$/u.test(ijLemma)) {
      const lemmaKey = `${ekLemma}\u0000${ijLemma}`;
      lemmaPairOccurrences.set(lemmaKey, (lemmaPairOccurrences.get(lemmaKey) || 0) + 1);
    }
  }

  const pairs = Array.from(pairOccurrences, ([key, count]) => {
    const [ekavianForm, ijekavianForm] = key.split("\u0000");
    return Object.freeze([ekavianForm, ijekavianForm, count]);
  }).sort((left, right) => left[0].localeCompare(right[0], "sr") || left[1].localeCompare(right[1], "sr"));

  const targetsByEkavian = new Map();
  const sourcesByIjekavian = new Map();
  for (const [ekavianForm, ijekavianForm] of pairs) {
    if (!targetsByEkavian.has(ekavianForm)) targetsByEkavian.set(ekavianForm, new Set());
    if (!sourcesByIjekavian.has(ijekavianForm)) sourcesByIjekavian.set(ijekavianForm, new Set());
    targetsByEkavian.get(ekavianForm).add(ijekavianForm);
    sourcesByIjekavian.get(ijekavianForm).add(ekavianForm);
  }

  const ambiguousEkavian = Array.from(targetsByEkavian)
    .filter(([, targets]) => targets.size > 1)
    .map(([form]) => form)
    .sort((left, right) => left.localeCompare(right, "sr"));
  const ambiguousIjekavian = Array.from(sourcesByIjekavian)
    .filter(([, sources]) => sources.size > 1)
    .map(([form]) => form)
    .sort((left, right) => left.localeCompare(right, "sr"));

  const lemmaPairs = Array.from(lemmaPairOccurrences, ([key, count]) => {
    const [ekavianLemma, ijekavianLemma] = key.split("\u0000");
    return Object.freeze([ekavianLemma, ijekavianLemma, count]);
  }).sort((left, right) => left[0].localeCompare(right[0], "sr") || left[1].localeCompare(right[1], "sr"));

  return Object.freeze({
    tokenCount: ekavian.length, pairs, lemmaPairs, ambiguousEkavian, ambiguousIjekavian
  });
}

function generatedModule(compiled) {
  const pairRows = compiled.pairs
    .map(([ekavian, ijekavian, count]) => `    ${JSON.stringify([ekavian, ijekavian, count])}`)
    .join(",\n");
  const lemmaRows = compiled.lemmaPairs
    .map(([ekavian, ijekavian, count]) => `    ${JSON.stringify([ekavian, ijekavian, count])}`)
    .join(",\n");
  return `// Generated by scripts/build-comtext-data.mjs. Do not edit manually.\n` +
`(function initialisePrepisiComtextData(root) {\n` +
`  "use strict";\n\n` +
`  if (root.PrepisiComtextData) return;\n` +
`  const api = Object.freeze({\n` +
`    source: "ICEF-NLP/COMtext.SR",\n` +
`    commit: "${COMMIT}",\n` +
`    tokenCount: ${compiled.tokenCount},\n` +
`    pairs: Object.freeze([\n${pairRows}\n    ].map((row) => Object.freeze(row))),\n` +
`    lemmaPairs: Object.freeze([\n${lemmaRows}\n    ].map((row) => Object.freeze(row))),\n` +
`    ambiguousEkavian: Object.freeze(${JSON.stringify(compiled.ambiguousEkavian)}),\n` +
`    ambiguousIjekavian: Object.freeze(${JSON.stringify(compiled.ambiguousIjekavian)})\n` +
`  });\n\n` +
`  root.PrepisiComtextData = api;\n` +
`  if (typeof module !== "undefined" && module.exports) module.exports = api;\n` +
`})(typeof globalThis !== "undefined" ? globalThis : this);\n`;
}

const [ekavianText, ijekavianText] = await Promise.all([
  download(SOURCES.ekavian),
  download(SOURCES.ijekavian)
]);
const compiled = compile(ekavianText, ijekavianText);
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputDirectory = path.join(projectRoot, "src", "generated");
const outputPath = path.join(outputDirectory, "comtext-pairs.js");
await mkdir(outputDirectory, { recursive: true });
await writeFile(outputPath, generatedModule(compiled), "utf8");

console.log(JSON.stringify({
  outputPath,
  tokenCount: compiled.tokenCount,
  distinctPairs: compiled.pairs.length,
  distinctLemmaPairs: compiled.lemmaPairs.length,
  ambiguousEkavianForms: compiled.ambiguousEkavian.length,
  ambiguousIjekavianForms: compiled.ambiguousIjekavian.length
}, null, 2));
